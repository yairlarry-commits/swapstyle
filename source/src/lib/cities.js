export function cityKey(name) {
  if (!name) return '';
  let k = String(name).toLowerCase().replace(/["'״׳\-–\s.,]/g, '');
  k = k.replace(/^קרית/, 'קריית');
  return ALIASES[k] ?? k;
}

export const sameCity = (a, b) => !!cityKey(a) && cityKey(a) === cityKey(b);
